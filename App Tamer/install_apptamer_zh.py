DEFAULT_TARGET = "/Applications/App Tamer.app/Contents/Resources/zh.lproj"


def main():
    target = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_TARGET
    if not os.path.isdir(os.path.dirname(target)):
        print("错误: 未找到 %s" % os.path.dirname(target))
        print("请确认 App Tamer 已安装（/Applications/App Tamer.app）")
        sys.exit(1)
    try:
        os.makedirs(target, exist_ok=True)
    except PermissionError:
        print("权限不足: 无法写入 %s" % target)
        print("请使用: sudo python3 install_apptamer_zh.py")
        sys.exit(1)

    for name, (enc, pairs) in FILES.items():
        content = "".join('"%s" = "%s";\n' % (k, v) for k, v in pairs)
        with open(os.path.join(target, name), "w", encoding=enc, newline="") as f:
            f.write(content)
        print("已生成 %s (%d 条, %s)" % (name, len(pairs), enc))

    print("\n完成！共写入 %d 个文件。请重启 App Tamer 使中文化生效。" % len(FILES))


if __name__ == "__main__":
    main()
